// Ranks countries from most to least confident and lists every entry per country,
// strongest evidence first. Writes research/confidence-by-country.md.
//
// Usage: node scripts/confidence-report.mjs
//
// Source tiers (by domain). Unknown domains default to tier 3; when unsure, a domain
// is placed in the LOWER tier on purpose.
//   1 official      — regulators, health ministries, government/embassy guidance
//   2 professional  — professional drug references, manufacturer pages, medical literature
//   3 secondary     — retailers, general drug sites, encyclopedias, news, blogs, travel sites

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DRUGS = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/drugs.json'), 'utf8'));
const COUNTRY_NAMES = {
  US: 'United States', GB: 'United Kingdom', CA: 'Canada', DE: 'Germany', FR: 'France', MX: 'Mexico',
  IN: 'India', ET: 'Ethiopia', JP: 'Japan', VN: 'Vietnam', SG: 'Singapore', MA: 'Morocco', PT: 'Portugal', TR: 'Türkiye',
};

export const TIER_1 = [
  'health-products.canada.ca', 'ndf.gov.sg', 'infarmed.pt', 'base-donnees-publique.medicaments.gouv.fr',
  'ansm.sante.fr', 'has-sante.fr', 'us.emb-japan.go.jp', 'info.pmda.go.jp', 'gob.mx', 'efda.gov.et',
  'ema.europa.eu', 'fda.gov', 'hweclinicalguidance.nhs.uk',
  // registries checked by scripts/verify
  'nlm.nih.gov', 'data.gov.sg',
];
export const TIER_2 = [
  'medicines.org.uk', 'gelbe-liste.de', 'vidal.fr', 'mims.com', 'vademecum.es', 'flexikon.doccheck.com',
  'rad-ar.or.jp', 'medical.nikkeibp.co.jp', 'deutsche-apotheker-zeitung.de',
  'pubmed.ncbi.nlm.nih.gov', 'pmc.ncbi.nlm.nih.gov', 'ncbi.nlm.nih.gov', 'annalsofoncology.org',
  // manufacturers / marketing-authorisation holders
  'eisai.com', 'sumitomo-pharma.com', 'organonpro.com', 'medice.com', 'ssp.co.jp', 'catalog-taisho.com',
  'flunase.jp', 'pfizer.pt', 'ben-u-ron.pt', 'loranopro.de', 'pyrocalmcontrol.co.uk',
];

export function sourceTier(source) {
  if (!source) return 0;
  let host;
  try { host = new URL(source).hostname.replace(/^www\./, ''); } catch { return 3; }
  const match = (list) => list.some((d) => host === d || host.endsWith('.' + d));
  return match(TIER_1) ? 1 : match(TIER_2) ? 2 : 3;
}

const CONF_RANK = { high: 0, medium: 1, low: 2 };
const TIER_RANK = { 1: 0, 2: 1, 3: 2, 0: 3 };
const RISKY = new Set(['BANNED', 'CONTROLLED']);

const rows = [];
for (const d of DRUGS) {
  for (const [code, e] of Object.entries(d.countries)) {
    // An entry confirmed by scripts/verify cites the registry record when it has no hand-picked source.
    const source = e.source ?? e.verified?.url ?? null;
    rows.push({ code, drug: d.generic, id: d.id, ...e, source, tier: sourceTier(source) });
  }
}

const countries = Object.keys(COUNTRY_NAMES).map((code) => {
  const list = rows.filter((r) => r.code === code);
  const n = list.length;
  const count = (f) => list.filter(f).length;
  const high = count((r) => r.confidence === 'high');
  const medium = count((r) => r.confidence === 'medium');
  const low = count((r) => r.confidence === 'low');
  return {
    code, name: COUNTRY_NAMES[code], n, high, medium, low,
    // Confidence score: high = 1, medium = 0.5, low = 0, averaged → 0–100.
    score: Math.round(((high + medium * 0.5) / n) * 100),
    t1: count((r) => r.tier === 1), t2: count((r) => r.tier === 2), t3: count((r) => r.tier === 3),
    unsourced: count((r) => r.tier === 0),
    highUnsourced: count((r) => r.confidence === 'high' && r.tier === 0),
    verified: count((r) => r.verified),
    risky: count((r) => RISKY.has(r.status)),
    riskyWeak: count((r) => RISKY.has(r.status) && (r.tier === 0 || r.tier === 3)),
    list: list.sort(
      (a, b) => CONF_RANK[a.confidence] - CONF_RANK[b.confidence] || TIER_RANK[a.tier] - TIER_RANK[b.tier] || a.drug.localeCompare(b.drug),
    ),
  };
}).sort((a, b) => b.score - a.score || (b.t1 + b.t2) - (a.t1 + a.t2));

// ---- Markdown report ----
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const totals = countries.reduce((t, c) => {
  for (const k of ['n', 'high', 'medium', 'low', 't1', 't2', 't3', 'unsourced', 'highUnsourced', 'verified', 'risky', 'riskyWeak']) t[k] = (t[k] ?? 0) + c[k];
  return t;
}, {});

let md = `# Confidence by country

Generated by \`scripts/confidence-report.mjs\` from \`src/data/drugs.json\` — re-run after data changes.

**Confidence score** = average of entry confidence (high = 1, medium = 0.5, low = 0), as a percentage.
**Source tiers:** T1 official (regulator, ministry, embassy) · T2 professional (drug reference, manufacturer,
literature) · T3 secondary (retailer, general site, encyclopedia, blog). The confidence labels were set by hand
when the data was researched; the tiers show how much evidence actually backs them.
**Verified** counts entries that \`scripts/verify/run.mjs\` confirmed against the country's official registry.

## Ranking (most → least confident)

| # | Country | Score | High | Med | Low | T1 | T2 | T3 | No source | High w/o source | Verified | Controlled/banned | …with weak/no source |
|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|
${countries.map((c, i) => `| ${i + 1} | ${c.code} ${c.name} | ${c.score} | ${c.high} | ${c.medium} | ${c.low} | ${c.t1} | ${c.t2} | ${c.t3} | ${c.unsourced} | ${c.highUnsourced} | ${c.verified} | ${c.risky} | ${c.riskyWeak} |`).join('\n')}
| | **All** | ${Math.round(((totals.high + totals.medium * 0.5) / totals.n) * 100)} | ${totals.high} | ${totals.medium} | ${totals.low} | ${totals.t1} | ${totals.t2} | ${totals.t3} | ${totals.unsourced} | ${totals.highUnsourced} | ${totals.verified} | ${totals.risky} | ${totals.riskyWeak} |

`;

for (const [i, c] of countries.entries()) {
  md += `## ${i + 1}. ${c.name} (${c.code}) — score ${c.score}\n\n`;
  md += `${c.high} high · ${c.medium} medium · ${c.low} low · sources: ${c.t1} official, ${c.t2} professional, ${c.t3} secondary, ${c.unsourced} none · ${c.verified} registry-verified\n\n`;
  md += `| Confidence | Medicine | Sold as | Status | Source |\n|---|---|---|---|---|\n`;
  for (const r of c.list) {
    const src = r.source ? `T${r.tier} [${new URL(r.source).hostname.replace(/^www\./, '')}](${r.source})` : '—';
    md += `| ${r.confidence}${r.verified ? ' ✓' : ''} | ${esc(r.drug)} | ${esc(r.brand)} | ${r.status}${RISKY.has(r.status) ? ' ⚠' : ''} | ${src} |\n`;
  }
  md += '\n';
}

const out = path.join(ROOT, 'research/confidence-by-country.md');
fs.writeFileSync(out, md);

// ---- Console summary ----
