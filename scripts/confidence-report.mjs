const lpad = (s, n) => String(s).padStart(n);
console.log(`${pad('#', 3)}${pad('Country', 18)}${lpad('Score', 6)}${lpad('High', 6)}${lpad('Med', 5)}${lpad('Low', 5)}${lpad('T1', 5)}${lpad('T2', 5)}${lpad('T3', 5)}${lpad('None', 6)}${lpad('Hi∅src', 8)}${lpad('Risky', 7)}${lpad('Rsk∅', 6)}`);
for (const [i, c] of countries.entries()) {
  console.log(`${pad(i + 1, 3)}${pad(`${c.code} ${c.name}`, 18)}${lpad(c.score, 6)}${lpad(c.high, 6)}${lpad(c.medium, 5)}${lpad(c.low, 5)}${lpad(c.t1, 5)}${lpad(c.t2, 5)}${lpad(c.t3, 5)}${lpad(c.unsourced, 6)}${lpad(c.highUnsourced, 8)}${lpad(c.risky, 7)}${lpad(c.riskyWeak, 6)}`);
}
console.log(`\nTiers: ${totals.t1} official, ${totals.t2} professional, ${totals.t3} secondary, ${totals.unsourced} unsourced (of ${totals.n})`);
console.log(`Wrote ${path.relative(ROOT, out)}`);
