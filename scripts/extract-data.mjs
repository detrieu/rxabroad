// Extracts the formulary data from the original single-file prototype
// (~/pill-trotter/pill-trotter-aug27.html) into typed TypeScript modules.
//
// Usage: node scripts/extract-data.mjs [path/to/source.html]
//        node scripts/extract-data.mjs --check   (verify src/data matches the source)

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const SRC = args.find((a) => !a.startsWith('--')) ?? path.join(os.homedir(), 'pill-trotter', 'pill-trotter-aug27.html');

export function loadFromHtml(file) {
  const html = fs.readFileSync(file, 'utf8');
  const start = html.indexOf('var COUNTRIES = [');
  const end = html.indexOf('var listEl');
  if (start < 0 || end < 0) throw new Error('Could not find data block in ' + file);
  const code = html.slice(start, end) + '\n;({ COUNTRIES, DRUGS, STATUS });';
  return vm.runInNewContext(code, {});
}

const SLUGS = {
  US: 'united-states', GB: 'united-kingdom', CA: 'canada', DE: 'germany', FR: 'france',
  MX: 'mexico', IN: 'india', ET: 'ethiopia', JP: 'japan', VN: 'vietnam', SG: 'singapore',
  MA: 'morocco', PT: 'portugal', TR: 'turkiye',
};

function validate({ COUNTRIES, DRUGS, STATUS }) {
  assert.equal(COUNTRIES.length, 14, 'expected 14 countries');
  assert.equal(DRUGS.length, 50, 'expected 50 drugs');
  const ids = new Set();
  for (const d of DRUGS) {
    assert.ok(!ids.has(d.id), 'duplicate drug id ' + d.id);
    ids.add(d.id);
    for (const [code, e] of Object.entries(d.countries)) {
      assert.ok(SLUGS[code], `${d.id}: unknown country ${code}`);
      assert.ok(STATUS[e.status], `${d.id}/${code}: unknown status ${e.status}`);
      assert.ok(['high', 'medium', 'low'].includes(e.confidence), `${d.id}/${code}: bad confidence`);
    }
  }
  // Spot check: aug27 carries the verified India research.
  const hctz = DRUGS.find((d) => d.id === 'hydrochlorothiazide').countries.IN;
  assert.equal(hctz.brand, 'Aquazide (Aquazide H)');
  assert.equal(hctz.confidence, 'high');
}

const json = (v) => JSON.stringify(v, null, 2);
const header = `// Generated by scripts/extract-data.mjs from the original prototype. Edit freely —\n// this file is now the source of truth.\n`;

const data = loadFromHtml(SRC);
// Normalize through JSON so vm-context objects compare cleanly.
const plain = JSON.parse(JSON.stringify(data));
validate(plain);

if (check) {
  const { DRUGS } = await import(path.join(ROOT, 'src/data/drugs.json'), { with: { type: 'json' } }).then((m) => ({ DRUGS: m.default }));
  assert.deepEqual(DRUGS, plain.DRUGS);
  console.log(`OK: src/data/drugs.json deep-equals ${path.basename(SRC)} (${DRUGS.length} drugs)`);
  process.exit(0);
}

const countries = plain.COUNTRIES.map((c) => ({ ...c, slug: SLUGS[c.code] }));
const outDir = path.join(ROOT, 'src/data');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'drugs.json'), json(plain.DRUGS) + '\n');
fs.writeFileSync(
  path.join(outDir, 'countries.ts'),
  header + `import type { Country } from './types';\n\nexport const COUNTRIES = ${json(countries)} as const satisfies readonly Country[];\n`,
);
fs.writeFileSync(
  path.join(outDir, 'status.ts'),
  header + `import type { StatusMeta } from './types';\n\nexport const STATUS = ${json(plain.STATUS)} as const satisfies Record<string, StatusMeta>;\n`,
);
const entries = plain.DRUGS.reduce((n, d) => n + Object.keys(d.countries).length, 0);
console.log(`Wrote ${plain.DRUGS.length} drugs (${entries} country entries), ${countries.length} countries to src/data/`);
